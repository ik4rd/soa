import subprocess
from pathlib import Path

import yaml

root = Path(__file__).parent
spec = yaml.safe_load((root / "openapi/marketplace.yaml").read_text())

out = root / "app/generated"
out.mkdir(exist_ok=True)
(out / "__init__.py").touch()

subprocess.run(
    [
        "datamodel-codegen",
        "--input",
        str(root / "openapi/marketplace.yaml"),
        "--input-file-type",
        "openapi",
        "--output",
        str(out / "models.py"),
        "--output-model-type",
        "pydantic_v2.BaseModel",
        "--field-constraints",
        "--use-standard-collections",
        "--use-union-operator",
        "--strict-nullable",
        "--base-class",
        "app.common.APIModel",
        "--strict-types",
        "str",
        "int",
        "bool",
        "--disable-timestamp",
        "--target-python-version",
        "3.13",
        "--formatters",
        "builtin",
    ],
    check=True,
)

lines = [
    "# Generated by generate.py; do not edit.",
    "from uuid import UUID",
    "from fastapi import APIRouter, Request, Query",
    "from .models import *",
    "from .. import service",
    "router = APIRouter()",
]

for path, methods in spec["paths"].items():
    for method, op in methods.items():
        args, passed = ["request: Request"], ["request"]
        if "requestBody" in op:
            model = op["requestBody"]["content"]["application/json"]["schema"][
                "$ref"
            ].split("/")[-1]
            args.append(f"body: {model}")
            passed.append("body=body")
        for p in op.get("parameters", []):
            s, name = p["schema"], p["name"]
            typ = (
                s.get("$ref", "").split("/")[-1]
                or {"integer": "int", "string": "str"}[s["type"]]
            )
            if s.get("format") == "uuid":
                typ = "UUID"
            if p["in"] == "path":
                args.append(f"{name}: {typ}")
            else:
                opts = [repr(s.get("default"))]
                if "default" not in s:
                    typ += " | None"
                for source, dest in [
                    ("minimum", "ge"),
                    ("maximum", "le"),
                    ("minLength", "min_length"),
                    ("maxLength", "max_length"),
                ]:
                    if source in s:
                        opts.append(f"{dest}={s[source]!r}")
                args.append(f"{name}: {typ} = Query({', '.join(opts)})")
            passed.append(f"{name}={name}")
        status, response = next(iter(op["responses"].items()))
        model = response["content"]["application/json"]["schema"]["$ref"].split("/")[-1]
        name = op["operationId"]
        lines += [
            f"@router.{method}({path!r}, response_model={model}, status_code={status})",
            f"def {name}({', '.join(args)}):",
            f"    return service.{name}({', '.join(passed)})",
            "",
        ]

(out / "routes.py").write_text("\n".join(lines))
